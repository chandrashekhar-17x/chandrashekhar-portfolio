// Generates TypeScript types from content/schemas/*.schema.json.
// The JSON Schemas are the single contract for content; never edit the output by hand.
//   pnpm gen:types     → write src/app/core/content/content.types.gen.ts
//   pnpm check:types   → fail if that file is out of date (used by make lint / CI)
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { compile } from 'json-schema-to-typescript';
import prettier from 'prettier';

const schemaDir = resolve(import.meta.dirname, '../../../content/schemas');
const outFile = resolve(import.meta.dirname, '../src/app/core/content/content.types.gen.ts');
const files = ['profile', 'skills', 'experience', 'projects', 'graph', 'lab'];
const checkOnly = process.argv.includes('--check');

// One bundle schema that references every file, so shared types are emitted once.
const bundle = {
  title: 'ContentBundle',
  type: 'object',
  additionalProperties: false,
  required: files,
  properties: Object.fromEntries(files.map((f) => [f, { $ref: `${f}.schema.json` }])),
};

const raw = await compile(bundle, 'ContentBundle', {
  cwd: schemaDir,
  bannerComment:
    '/* eslint-disable */\n// AUTO-GENERATED by scripts/gen-content-types.mjs from content/schemas. Do not edit.',
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
  unreachableDefinitions: false,
});
// Format with the repo's prettier config so the output is stable.
const options = (await prettier.resolveConfig(outFile)) ?? {};
const ts = await prettier.format(raw, { ...options, filepath: outFile });

if (checkOnly) {
  const current = await readFile(outFile, 'utf8').catch(() => '');
  if (current !== ts) {
    console.error(
      '✗ content.types.gen.ts is out of date. Run: pnpm --filter @portfolio/web gen:types',
    );
    process.exit(1);
  }
  console.log('✓ content types are up to date');
} else {
  await writeFile(outFile, ts);
  console.log(`✓ wrote ${outFile}`);
}
