// Generates TypeScript types from content/schemas/*.schema.json.
// The JSON Schemas are the single contract for content; never edit the output by hand.
// Usage: pnpm gen:types   (CI fails if the committed file is out of date)
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { compile } from 'json-schema-to-typescript';

const schemaDir = resolve(import.meta.dirname, '../../../content/schemas');
const outFile = resolve(import.meta.dirname, '../src/app/core/content/content.types.gen.ts');
const files = ['profile', 'skills', 'experience', 'projects', 'graph', 'lab'];

// One bundle schema that references every file, so shared types are emitted once.
const bundle = {
  title: 'ContentBundle',
  type: 'object',
  additionalProperties: false,
  required: files,
  properties: Object.fromEntries(files.map((f) => [f, { $ref: `${f}.schema.json` }])),
};

const ts = await compile(bundle, 'ContentBundle', {
  cwd: schemaDir,
  bannerComment:
    '/* eslint-disable */\n// AUTO-GENERATED by scripts/gen-content-types.mjs from content/schemas. Do not edit.',
  additionalProperties: false,
  ignoreMinAndMaxItems: true,
  unreachableDefinitions: false,
  style: { singleQuote: true, printWidth: 100 },
});
await writeFile(outFile, ts);
console.log(`✓ wrote ${outFile}`);
