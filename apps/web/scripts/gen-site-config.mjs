import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildInfo } from './build-info.mjs';
import { apiOrigin, siteOrigin } from './site-origin.mjs';

// Only public origins are emitted; secrets from .env never enter the browser.
const envFile = fileURLToPath(new URL('../../../.env', import.meta.url));
if (existsSync(envFile)) process.loadEnvFile(envFile);

const origin = siteOrigin(process.env.PUBLIC_SITE_URL);
const api = apiOrigin(process.env.PUBLIC_API_URL);
// Content comes from the API only on request: a free API host that sleeps would make
// every page wait for a cold start. Default: bundled content/, API for contact (+ chat).
const contentFromApi = api !== null && process.env.PUBLIC_CONTENT_SOURCE?.trim() === 'api';
// Turnstile site keys are public by design (the secret key stays on the API).
const turnstileKey = process.env.TURNSTILE_SITE_KEY?.trim() || null;

const output = new URL('../src/app/core/seo/site-origin.gen.ts', import.meta.url);
const source = [
  '// Generated by scripts/gen-site-config.mjs; do not edit.',
  `export const SITE_ORIGIN = ${JSON.stringify(origin)};`,
  '/** API origin (PUBLIC_API_URL) for the contact form and chat; null = no backend. */',
  `export const API_ORIGIN: string | null = ${JSON.stringify(api)};`,
  '/** PUBLIC_CONTENT_SOURCE=api: read content from the API instead of the bundled files. */',
  `export const CONTENT_FROM_API: boolean = ${JSON.stringify(contentFromApi)};`,
  '/** Public Cloudflare Turnstile site key; null = no bot-check widget. */',
  `export const TURNSTILE_SITE_KEY: string | null = ${JSON.stringify(turnstileKey)};`,
  '/** Latest commit in this build (footer stamp, source links); null outside git. */',
  `export const BUILD_INFO: { sha: string; date: string | null; subject: string } | null = ${JSON.stringify(buildInfo())};`,
  '',
].join('\n');
mkdirSync(new URL('.', output), { recursive: true });
if (!existsSync(output) || readFileSync(output, 'utf8') !== source) {
  writeFileSync(output, source);
}
